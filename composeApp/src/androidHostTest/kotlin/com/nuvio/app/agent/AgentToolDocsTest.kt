package com.nuvio.app.agent

import com.nuvio.app.agent.core.AgentTool
import com.nuvio.app.agent.core.ToolCategory
import com.nuvio.app.agent.tools.AgentToolCoverage
import com.nuvio.app.agent.tools.agentSettings
import java.io.File
import kotlin.test.Test
import kotlin.test.assertEquals

/**
 * docs/agent-tools.md is generated from the live registry so it can never drift from the code.
 * Regenerate with:  UPDATE_AGENT_DOCS=1 ./gradlew :composeApp:testAndroidHostTest --tests '*AgentToolDocsTest*'
 */
class AgentToolDocsTest {
    @Test
    fun agentToolsDocIsUpToDate() {
        val docFile = listOf("../docs/agent-tools.md", "docs/agent-tools.md").map(::File).firstOrNull { it.parentFile?.exists() == true }
            ?: File("../docs/agent-tools.md")
        val expected = render(fullCatalog().all)
        if (System.getenv("UPDATE_AGENT_DOCS") == "1") {
            docFile.parentFile?.mkdirs()
            docFile.writeText(expected)
        }
        assertEquals(expected, docFile.takeIf { it.exists() }?.readText(), "docs/agent-tools.md is stale; regenerate with UPDATE_AGENT_DOCS=1 (see test KDoc)")
    }

    private fun render(tools: List<AgentTool>): String = buildString {
        appendLine("# In-app assistant: tool reference")
        appendLine()
        appendLine("<!-- Generated by AgentToolDocsTest from the live tool registry. Do not edit by hand. -->")
        appendLine()
        appendLine("The assistant controls Nuvio through **${tools.size} tools**. Each tool has a name, a description the model reads, a JSON-schema for its parameters and returns a JSON object (`{\"ok\": true, …}` or `{\"ok\": false, \"error\": …, \"code\": …}`).")
        appendLine("Tools marked **⚠ confirm** show a confirmation dialog and only run if the user approves. Tools marked **parallel** are read-only and may run concurrently when the model issues several calls at once.")
        appendLine()
        appendLine("## Capability inventory")
        appendLine()
        appendLine("Nuvio has no ViewModels: every screen reads state from singleton repositories (`object …Repository` in `composeApp/src/commonMain`) and navigates through `NuvioNavigator`. The assistant reaches the same entry points:")
        appendLine()
        appendLine("| Area | App entry points | Agent tools |")
        appendLine("|---|---|---|")
        INVENTORY.forEach { (area, entry, toolNames) -> appendLine("| $area | $entry | ${toolNames.joinToString(", ") { "`$it`" }} |") }
        appendLine()
        appendLine("Navigation destinations (`AppRoute`): Home/Search/Library/Settings tabs → `open_tab`; title details (`DetailRoute`) → `open_title`; person (`PersonDetailRoute`) → `open_person`; catalog page (`CatalogRoute`) → `open_catalog`; stream picker (`StreamRoute`) → `play_title`; player (`PlayerRoute`) → `play_stream`; downloads (`DownloadsRoute`) → `open_downloads`; every settings page (addons, plugins, account, playback, streams, appearance, home screen, title page, continue watching, collections, integrations, notifications, debrid, licenses…) → `open_settings`; back → `go_back`.")
        appendLine()
        ToolCategory.entries.forEach { category ->
            val inCategory = tools.filter { it.category == category }
            if (inCategory.isEmpty()) return@forEach
            appendLine("## ${category.title}")
            appendLine()
            inCategory.forEach { tool ->
                val flags = listOfNotNull("⚠ confirm".takeIf { tool.requiresConfirmation }, "parallel".takeIf { tool.readOnly }).joinToString(" · ")
                appendLine("### `${tool.name}`${if (flags.isNotEmpty()) " — $flags" else ""}")
                appendLine()
                appendLine(tool.description.replace(Regex("\\s*\\n\\s*"), " "))
                appendLine()
                if (tool.params.isNotEmpty()) {
                    appendLine("| Parameter | Type | Required | Description |")
                    appendLine("|---|---|---|---|")
                    tool.params.forEach { p ->
                        val type = p.enum?.joinToString(" \\| ") { "`$it`" } ?: p.type
                        appendLine("| `${p.name}` | $type | ${if (p.required) "yes" else ""} | ${p.description.replace("|", "\\|")} |")
                    }
                    appendLine()
                }
                val covers = tool.covers.filter { it.substringBefore('.').let { owner -> owner.endsWith("Repository") || owner.startsWith("Agent") } }
                if (covers.isNotEmpty() && tool.name != "set_setting") {
                    appendLine("Calls: ${covers.joinToString(", ") { "`$it`" }}")
                    appendLine()
                }
            }
        }
        appendLine("## Settings reachable through `set_setting`")
        appendLine()
        appendLine("| Key | Type / options | Description | Repository setter |")
        appendLine("|---|---|---|---|")
        agentSettings.forEach { s ->
            appendLine("| `${s.key}` | ${s.options?.joinToString(", ") ?: s.type} | ${s.description} | `${s.covers}` |")
        }
        appendLine()
        appendLine("## Not exposed as tools (and why)")
        appendLine()
        appendLine("`AgentToolCatalogTest.everyPublicAppActionHasAToolOrADocumentedExemption` reflects over these owners and fails if a public member is neither covered by a tool nor listed here: ${AgentToolCoverage.OWNERS.joinToString(", ") { "`${it.substringAfterLast('.')}`" }}.")
        appendLine()
        AgentToolCoverage.EXEMPTIONS.entries.groupBy({ it.value }, { it.key }).forEach { (reason, members) ->
            appendLine("- **$reason** ${members.sorted().joinToString(", ") { "`$it`" }}")
        }
    }

    private companion object {
        val INVENTORY = listOf(
            Triple("Screen state", "`AgentBridge.navigation` (route, back stack, tab), screen repositories' `uiState`", listOf("get_app_state", "get_visible_items")),
            Triple("Navigation", "`NuvioNavigator`, `AppScreenTab`, `CatalogLaunchStore`", listOf("open_tab", "go_back", "open_title", "open_person", "open_catalog", "open_settings", "open_downloads")),
            Triple("Search & discover", "`SearchRepository`, `SearchHistoryRepository`, `HomeRepository`, `CatalogRepository`", listOf("search_titles", "discover", "list_home_rows", "get_catalog_page", "get_search_history", "remove_search_history_entry")),
            Triple("Title details", "`MetaDetailsRepository`", listOf("get_title_details", "list_episodes")),
            Triple("Streams", "`StreamsRepository`, stream picker (`AgentStreamScreenHandle`)", listOf("play_title", "list_streams", "filter_streams_by_addon", "play_stream", "download_stream")),
            Triple("Player", "player runtime (`AgentPlayerHandle`: play/pause/seek/speed/tracks/subtitles/next episode/close)", listOf("get_player_state", "player_pause", "player_resume", "player_seek", "player_set_speed", "player_select_audio", "player_select_subtitles", "player_set_subtitle_delay", "player_next_episode", "player_close")),
            Triple("Library", "`LibraryRepository`", listOf("get_library", "is_in_library", "add_to_library", "remove_from_library", "clear_library")),
            Triple("Progress & watched", "`WatchProgressRepository`, `WatchedRepository`", listOf("get_continue_watching", "get_watch_progress", "remove_from_continue_watching", "set_watched", "is_watched")),
            Triple("Addons", "`AddonRepository`", listOf("list_addons", "install_addon", "remove_addon", "set_addon_enabled", "move_addon", "refresh_addons")),
            Triple("Settings", "`PlayerSettingsRepository`, `ThemeSettingsRepository`, `MetaScreenSettingsRepository`, `ContinueWatchingPreferencesRepository`, `HomeCatalogSettingsRepository`, `SearchHistoryRepository`", listOf("list_settings", "set_setting", "list_home_rows_settings", "configure_home_row", "reset_home_rows", "reset_details_layout")),
            Triple("Account & profiles", "`AuthRepository`, `ProfileRepository`", listOf("get_account", "switch_profile", "sign_out")),
            Triple("Downloads", "`DownloadsRepository`", listOf("list_downloads", "download_stream", "manage_download")),
            Triple("Collections", "`CollectionRepository`", listOf("list_collections", "delete_collection", "move_collection")),
            Triple("Web", "built-in", listOf("web_search", "fetch_url")),
            Triple("Stremio addon protocol", "built-in (manifest, /catalog, /meta, /stream, /subtitles)", listOf("addon_manifest", "addon_catalog", "addon_meta", "addon_streams", "addon_subtitles")),
            Triple("Utilities & memory", "built-in", listOf("calculate", "get_current_time", "remember", "recall", "forget")),
        )
    }
}
